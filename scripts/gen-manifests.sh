#!/usr/bin/env bash
# gen-manifests.sh VERSION DATE SHA256SUMS OUTDIR — write the package
# manifests of a release from its SHA256SUMS file (every download is pinned
# by SHA-256):
#
#   OUTDIR/homebrew/Formula/kmd.rb                  Homebrew tap formula
#   OUTDIR/aur/PKGBUILD, OUTDIR/aur/.SRCINFO        AUR package kmd-bin
#   OUTDIR/scoop/bucket/kmd.json                    Scoop bucket manifest
#   OUTDIR/winget/manifests/d/DipaolaFederico/kmd/VERSION/*.yaml   winget
#
# The release workflow runs it in each channel job, from the released commit
# and the release's attested SHA256SUMS (see .github/workflows/release.yml).
set -euo pipefail

ver=$1 date=$2 sums=$3 out=$4
[[ $ver =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "gen-manifests: bad version '$ver'" >&2; exit 2; }
[[ $date =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || { echo "gen-manifests: bad date '$date'" >&2; exit 2; }

repo=https://github.com/DipaolaFederico/kmd
dl=$repo/releases/download/v$ver
desc="Fast, beautiful Markdown previewer for the terminal"
maint="Federico Di Paola <65874112+DipaolaFederico@users.noreply.github.com>"

# sha PLATFORM EXT — the checksum of kmd-vVERSION-PLATFORM.EXT in SHA256SUMS
sha() {
  local name=kmd-v$ver-$1.$2 sum
  sum=$(awk -v f="$name" '$2 == f || $2 == "*" f { print $1; exit }' "$sums")
  [[ $sum =~ ^[0-9a-f]{64}$ ]] || { echo "gen-manifests: no SHA-256 for $name in $sums" >&2; exit 1; }
  echo "$sum"
}
darwin_arm64=$(sha darwin-arm64 tar.gz)
darwin_amd64=$(sha darwin-amd64 tar.gz)
linux_arm64=$(sha linux-arm64 tar.gz)
linux_amd64=$(sha linux-amd64 tar.gz)
windows_amd64=$(sha windows-amd64 zip)

mkdir -p "$out/homebrew/Formula" "$out/aur" "$out/scoop/bucket"
wdir=$out/winget/manifests/d/DipaolaFederico/kmd/$ver
mkdir -p "$wdir"

## Homebrew -------------------------------------------------------------------
cat >"$out/homebrew/Formula/kmd.rb" <<EOF
# Generated by the kmd release workflow (scripts/gen-manifests.sh): do not edit.
class Kmd < Formula
  desc "$desc"
  homepage "$repo"
  version "$ver"
  license "MIT"

  on_macos do
    on_arm do
      url "$dl/kmd-v$ver-darwin-arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$dl/kmd-v$ver-darwin-amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$dl/kmd-v$ver-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$dl/kmd-v$ver-linux-amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "kmd"
    man1.install "kmd.1"
    generate_completions_from_executable(bin/"kmd", "--completion")
  end

  test do
    assert_equal "kmd v#{version}", shell_output("#{bin}/kmd --version").strip
    assert_match "HELLO", pipe_output("#{bin}/kmd -c never", "# Hello\\n")
  end
end
EOF

## AUR (kmd-bin) --------------------------------------------------------------
cat >"$out/aur/PKGBUILD" <<EOF
# Maintainer: $maint
# Generated by the kmd release workflow (scripts/gen-manifests.sh): do not edit.
pkgname=kmd-bin
pkgver=$ver
pkgrel=1
pkgdesc="$desc"
arch=('x86_64' 'aarch64')
url="$repo"
license=('MIT')
provides=('kmd')
conflicts=('kmd')
options=('!strip' '!debug')
source_x86_64=("kmd-v\${pkgver}-linux-amd64.tar.gz::\${url}/releases/download/v\${pkgver}/kmd-v\${pkgver}-linux-amd64.tar.gz")
source_aarch64=("kmd-v\${pkgver}-linux-arm64.tar.gz::\${url}/releases/download/v\${pkgver}/kmd-v\${pkgver}-linux-arm64.tar.gz")
sha256sums_x86_64=('$linux_amd64')
sha256sums_aarch64=('$linux_arm64')

package() {
  local dir=kmd-v\${pkgver}-linux-amd64
  [ "\$CARCH" = aarch64 ] && dir=kmd-v\${pkgver}-linux-arm64
  install -Dm755 "\$dir/kmd" "\$pkgdir/usr/bin/kmd"
  install -Dm644 "\$dir/kmd.1" "\$pkgdir/usr/share/man/man1/kmd.1"
  install -Dm644 "\$dir/LICENSE" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE"
  "\$dir/kmd" --completion bash | install -Dm644 /dev/stdin "\$pkgdir/usr/share/bash-completion/completions/kmd"
  "\$dir/kmd" --completion zsh | install -Dm644 /dev/stdin "\$pkgdir/usr/share/zsh/site-functions/_kmd"
  "\$dir/kmd" --completion fish | install -Dm644 /dev/stdin "\$pkgdir/usr/share/fish/vendor_completions.d/kmd.fish"
}
EOF

# what \`makepkg --printsrcinfo\` prints for the PKGBUILD above
cat >"$out/aur/.SRCINFO" <<EOF
pkgbase = kmd-bin
	pkgdesc = $desc
	pkgver = $ver
	pkgrel = 1
	url = $repo
	arch = x86_64
	arch = aarch64
	license = MIT
	provides = kmd
	conflicts = kmd
	options = !strip
	options = !debug
	source_x86_64 = kmd-v$ver-linux-amd64.tar.gz::$dl/kmd-v$ver-linux-amd64.tar.gz
	sha256sums_x86_64 = $linux_amd64
	source_aarch64 = kmd-v$ver-linux-arm64.tar.gz::$dl/kmd-v$ver-linux-arm64.tar.gz
	sha256sums_aarch64 = $linux_arm64

pkgname = kmd-bin
EOF

## Scoop ------------------------------------------------------------------------
cat >"$out/scoop/bucket/kmd.json" <<EOF
{
    "version": "$ver",
    "description": "$desc",
    "homepage": "$repo",
    "license": "MIT",
    "architecture": {
        "64bit": {
            "url": "$dl/kmd-v$ver-windows-amd64.zip",
            "hash": "$windows_amd64",
            "extract_dir": "kmd-v$ver-windows-amd64"
        }
    },
    "bin": "kmd.exe"
}
EOF

## winget -----------------------------------------------------------------------
schema=https://aka.ms/winget-manifest
mver=1.9.0
cat >"$wdir/DipaolaFederico.kmd.yaml" <<EOF
# yaml-language-server: \$schema=$schema.version.$mver.schema.json
PackageIdentifier: DipaolaFederico.kmd
PackageVersion: $ver
DefaultLocale: en-US
ManifestType: version
ManifestVersion: $mver
EOF
cat >"$wdir/DipaolaFederico.kmd.installer.yaml" <<EOF
# yaml-language-server: \$schema=$schema.installer.$mver.schema.json
PackageIdentifier: DipaolaFederico.kmd
PackageVersion: $ver
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
- RelativeFilePath: kmd-v$ver-windows-amd64\\kmd.exe
  PortableCommandAlias: kmd
Commands:
- kmd
ReleaseDate: $date
Installers:
- Architecture: x64
  InstallerUrl: $dl/kmd-v$ver-windows-amd64.zip
  InstallerSha256: ${windows_amd64^^}
ManifestType: installer
ManifestVersion: $mver
EOF
cat >"$wdir/DipaolaFederico.kmd.locale.en-US.yaml" <<EOF
# yaml-language-server: \$schema=$schema.defaultLocale.$mver.schema.json
PackageIdentifier: DipaolaFederico.kmd
PackageVersion: $ver
PackageLocale: en-US
Publisher: Federico Di Paola
PublisherUrl: https://github.com/DipaolaFederico
PublisherSupportUrl: $repo/issues
PackageName: kmd
PackageUrl: $repo
License: MIT
LicenseUrl: $repo/blob/v$ver/LICENSE
ShortDescription: $desc
Description: kmd renders Markdown files as rich, colorful previews in the terminal, with syntax highlighting, hyperlinks, images, diagrams, math, themes, a built-in viewer, presentations and HTML export.
Moniker: kmd
Tags:
- markdown
- terminal
- cli
- viewer
- preview
ReleaseNotesUrl: $repo/releases/tag/v$ver
ManifestType: defaultLocale
ManifestVersion: $mver
EOF

echo "manifests for $ver in $out"
